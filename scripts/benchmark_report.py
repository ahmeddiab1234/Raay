"""Render the benchmark table as Markdown and write the CSV sibling.

Both outputs are generated; never hand-edit ``reports/benchmark_table.md``.
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

from loguru import logger


def markdown_table(
    rows: list[dict[str, Any]],
    samples: int,
    batch_sizes: list[int],
    runs: int,
    max_length: int,
) -> str:
    """Build the README-ready comparison table for the given variants."""
    header = [
        "variant",
        "backend",
        "accuracy",
        "f1_macro",
        "batch1 p50 (ms)",
        "batch1 p95 (ms)",
        f"batch{max(batch_sizes)} p50 (ms)",
        f"batch{max(batch_sizes)} p95 (ms)",
        "size (MB)",
        "size vs baseline",
        "note",
    ]
    batch_size = max(batch_sizes)
    lines = ["# Benchmark table", ""]
    lines.append(
        f"_Auto-generated by `uv run python scripts/benchmark.py`. {samples} "
        f"held-out samples, {runs} pass(es), max_length={max_length}. batch1 = one "
        f"single-sample call; batch{max(batch_sizes)} = one call over a batch of "
        f"{max(batch_sizes)} (chunk-level latency)._"
    )
    lines += [
        "",
        "| " + " | ".join(header) + " |",
        "|" + "|".join(["---"] * len(header)) + "|",
    ]
    for row in rows:
        cells = [
            row["variant"],
            row["backend"],
            f"{row['accuracy']:.4f}",
            f"{row['f1_macro']:.4f}",
            f"{row['batch1_p50_ms']:.1f}",
            f"{row['batch1_p95_ms']:.1f}",
            f"{row[f'batch{batch_size}_p50_ms']:.1f}",
            f"{row[f'batch{batch_size}_p95_ms']:.1f}",
            f"{row['size_mb']:.1f}",
            str(row["size_vs_baseline"]),
            str(row["note"]),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def write_outputs(rows: list[dict[str, Any]], md: str, output_path: Path) -> None:
    """Write ``<stem>.md`` and ``<stem>.csv`` beside each other."""
    out_dir = output_path.parent
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{output_path.stem}.md").write_text(md)
    with open(output_path, "w", newline="") as f:
        fieldnames = list(rows[0].keys())
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    logger.info(f"Wrote {out_dir / f'{output_path.stem}.md'}")
    logger.info(f"Wrote {output_path}")
